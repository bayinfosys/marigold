"""Write the host config reference in docs/configuration.md from HostConfig.

The tables between the markers in docs/configuration.md are generated:
edit the Field descriptions in package/src/marigold/cli/host_config.py, then run

    python scripts/config_doc.py           # rewrite the tables
    python scripts/config_doc.py --check   # exit 1 if they are out of date

Everything outside the markers is written by hand.
"""

import argparse
import json
import sys
import typing

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "package" / "src"))

from pydantic import BaseModel  # noqa: E402
from pydantic_core import PydanticUndefined  # noqa: E402

from marigold.cli.host_config import HostConfig  # noqa: E402

DOC = ROOT / "docs" / "configuration.md"
START = "<!-- host-config:start (generated by scripts/config_doc.py) -->"
END = "<!-- host-config:end -->"


def show(value) -> str:
    """A default as it would be written in TOML."""
    if value is None:
        return "unset"

    if isinstance(value, bool):
        return f"`{str(value).lower()}`"

    if isinstance(value, Path):
        value = str(value).replace(str(Path.home()), "~", 1)

    if isinstance(value, str):
        return f'`"{value}"`'

    return f"`{json.dumps(value)}`"


def table(model: BaseModel) -> list[str]:
    lines = ["| Key | Default | Description |", "|---|---|---|"]

    for name, field in type(model).model_fields.items():
        value = getattr(model, name)
        if isinstance(value, BaseModel):
            continue
        lines.append(f"| `{name}` | {show(value)} | {field.description or ''} |")

    return lines


def class_table(model_cls: type[BaseModel]) -> list[str]:
    """A table for a model with no default instance, such as a list entry."""
    lines = ["| Key | Default | Description |", "|---|---|---|"]

    for name, field in model_cls.model_fields.items():
        default = "required" if field.default is PydanticUndefined else show(field.default)
        lines.append(f"| `{name}` | {default} | {field.description or ''} |")

    return lines


def list_item_model(annotation) -> type[BaseModel] | None:
    """The model in list[Model], or None."""
    if typing.get_origin(annotation) is list:
        (item,) = typing.get_args(annotation)
        if isinstance(item, type) and issubclass(item, BaseModel):
            return item
    return None


def render() -> str:
    host = HostConfig()
    out = [START, ""]

    for section, field in HostConfig.model_fields.items():
        value = getattr(host, section)
        item = list_item_model(field.annotation)

        if item is not None:
            out += [f"### `[[{section}]]`", "", field.description or "", ""] + class_table(item) + ["", "Default: none.", ""]
            continue

        if not isinstance(value, BaseModel):
            out += [f"### `[{section}]`", "", field.description or "", "", "Default: none.", ""]
            continue

        nested = {
            name: getattr(value, name)
            for name in type(value).model_fields
            if isinstance(getattr(value, name), BaseModel)
        }

        if not nested:
            out += [f"### `[{section}]`", ""] + table(value) + [""]
            continue

        out += [f"### `[{section}]`", ""]
        for name, sub in nested.items():
            description = type(value).model_fields[name].description or ""
            out += [f"#### `[{section}.{name}]`", "", description, ""] + table(sub) + [""]

    out.append(END)
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="exit 1 if the doc is out of date")
    args = parser.parse_args()

    text = DOC.read_text(encoding="utf-8")
    head, _, rest = text.partition(START)
    _, _, tail = rest.partition(END)

    if not rest:
        print(f"{DOC}: no '{START}' marker", file=sys.stderr)
        return 1

    updated = head + render() + tail

    if args.check:
        if updated != text:
            print(f"{DOC} is out of date: run python scripts/config_doc.py", file=sys.stderr)
            return 1
        return 0

    DOC.write_text(updated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
