"""OpenAI-compatible API endpoints.

Provides a subset of the OpenAI REST API as a synchronous wrapper around
the Marigold async submission and polling path, so any OpenAI-compatible
client (Open WebUI, LangChain, the openai SDK) can use Marigold without
modification.

Endpoints implemented
---------------------
GET  /v1/models                  list available models
POST /v1/chat/completions        instruct/chat inference
POST /v1/embeddings              text embedding

Streaming
---------
stream=true is accepted. Generation is still a single blocking call per
request, so the finished result is sent as a fixed sequence of SSE
chunks (role, then content and/or tool calls, then finish_reason)
followed by [DONE]. This is the framing OpenAI clients expect; it is not
token-level streaming.

Tool calling
------------
Tool calls carry ids in both directions. An assistant turn's calls keep
their ids, and a tool message's tool_call_id says which call it answers,
so several calls in one turn round-trip. Ids are generated by
shared.models.gen_tool_call_id, the same function the instruct handler
uses. tool_choice accepts "auto" and "none"; "required" and named
functions are rejected with 400.

Application identity
--------------------
The X-Marigold-Application-Id header, when present, becomes the request's
application_id, so usage from OpenAI clients is attributed to an
application.

Not implemented
----------------
Image generation, audio, fine-tuning -- not mapped.
"""

import asyncio
import json
import logging
import time
from typing import Literal

from fastapi import HTTPException, Request, APIRouter
from fastapi.responses import StreamingResponse
from models.catalogue import get_models_by_type
from pydantic import BaseModel, ValidationError
from shared.enums import ModelType, StatusCode
from shared.models import InstructToolCall, gen_tool_call_id
from shared.receiver_logic import handle_status, handle_submission

logger = logging.getLogger(__name__)

router = APIRouter()

_POLL_INTERVAL = 0.5  # seconds between polls
_MAX_WAIT = 300  # seconds before timing out

APPLICATION_HEADER = "x-marigold-application-id"


# ---------------------------------------------------------------------------
# Request / response models
# ---------------------------------------------------------------------------


class ToolCallFunction(BaseModel):
    name: str
    arguments: str  # JSON-encoded string, per OpenAI convention


class ToolCall(BaseModel):
    id: str
    type: str = "function"
    function: ToolCallFunction


class ToolCallDelta(ToolCall):
    """A tool call in a streamed chunk. Clients assemble calls by index."""

    index: int


class ChatMessage(BaseModel):
    role: Literal["system", "user", "assistant", "tool"]
    content: str | None = None
    tool_calls: list[ToolCall] | None = None
    tool_call_id: str | None = None
    name: str | None = None


class ChatCompletionRequest(BaseModel):
    model: str
    messages: list[ChatMessage]
    temperature: float = 1.0
    max_tokens: int = 1000
    top_p: float | None = None
    top_k: int | None = None
    seed: int | None = None
    stream: bool = False
    tools: list[dict] | None = None
    tool_choice: str | dict | None = None
    response_format: dict | None = None
    chat_template_kwargs: dict | None = None


class ChatCompletionChoice(BaseModel):
    index: int
    message: ChatMessage
    finish_reason: str = "stop"


class UsageStats(BaseModel):
    prompt_tokens: int
    completion_tokens: int
    total_tokens: int


class ChatCompletionResponse(BaseModel):
    id: str
    object: str = "chat.completion"
    created: int
    model: str
    choices: list[ChatCompletionChoice]
    usage: UsageStats


class ChatCompletionChunkDelta(BaseModel):
    role: str | None = None
    content: str | None = None
    tool_calls: list[ToolCallDelta] | None = None


class ChatCompletionChunkChoice(BaseModel):
    index: int = 0
    delta: ChatCompletionChunkDelta
    finish_reason: str | None = None


class ChatCompletionChunk(BaseModel):
    id: str
    object: str = "chat.completion.chunk"
    created: int
    model: str
    choices: list[ChatCompletionChunkChoice]


class EmbeddingRequest(BaseModel):
    model: str
    input: str | list[str]
    encoding_format: str = "float"


class EmbeddingData(BaseModel):
    object: str = "embedding"
    index: int
    embedding: list[float]


class EmbeddingResponse(BaseModel):
    object: str = "list"
    model: str
    data: list[EmbeddingData]
    usage: UsageStats


class ModelObject(BaseModel):
    id: str
    object: str = "model"
    created: int = 0
    owned_by: str = "marigold"


class ModelsResponse(BaseModel):
    object: str = "list"
    data: list[ModelObject]


# ---------------------------------------------------------------------------
# Errors
# ---------------------------------------------------------------------------


def _client_error(message: str) -> HTTPException:
    return HTTPException(
        status_code=400,
        detail={"error": {"message": message, "type": "invalid_request_error"}},
    )


def _check_tool_choice(tool_choice: str | dict | None) -> None:
    if tool_choice is None or tool_choice in ("auto", "none"):
        return

    shown = "a named function" if isinstance(tool_choice, dict) else repr(tool_choice)
    raise _client_error("tool_choice %s is not supported; use 'auto' or 'none'" % shown)


# ---------------------------------------------------------------------------
# Message shape conversion -- OpenAI <-> InstructMessage
# ---------------------------------------------------------------------------


def _to_instruct_message(m: ChatMessage) -> dict:
    """An OpenAI ChatMessage as the dict /gen/instruct's InstructMessage expects.

    Tool calls are validated here, so a malformed call is a 400 now
    rather than a failed job later.
    """
    d = {"role": m.role, "content": m.content}

    if m.tool_calls:
        try:
            d["tool_calls"] = [
                InstructToolCall.model_validate(tc.model_dump()).model_dump()
                for tc in m.tool_calls
            ]
        except ValidationError as e:
            raise _client_error("invalid tool call: %s" % e) from e

    if m.tool_call_id:
        d["tool_call_id"] = m.tool_call_id

    if m.name:
        d["name"] = m.name

    return d


def _from_instruct_tool_calls(raw_tool_calls: list[dict], message_id: str) -> list[ToolCall]:
    """InstructMessage tool calls (arguments as a dict) as OpenAI ToolCalls
    (arguments as a JSON string). Results stored without ids get the ids
    the handler would have given them."""
    calls = []

    for i, raw in enumerate(raw_tool_calls):
        tc = InstructToolCall.model_validate(raw)
        calls.append(
            ToolCall(
                id=tc.id or gen_tool_call_id(message_id, i),
                function=ToolCallFunction(
                    name=tc.function.name,
                    arguments=json.dumps(tc.function.arguments),
                ),
            )
        )

    return calls


# ---------------------------------------------------------------------------
# Polling
# ---------------------------------------------------------------------------


async def _poll(user_id: str, message_id: str, results_cache) -> tuple[int, dict]:
    """Poll until the job is terminal or the wait runs out.

    Returns (200, poll envelope), (404, {}) or (504, {}).
    """
    deadline = time.monotonic() + _MAX_WAIT

    while time.monotonic() < deadline:
        await asyncio.sleep(_POLL_INTERVAL)
        code, resp = handle_status(
            user_id=user_id,
            message_id=message_id,
            results_cache=results_cache,
        )
        if code == 200:
            return 200, resp
        if code == 404:
            return 404, {}

    return 504, {}


def _result_or_raise(status_code: int, poll: dict) -> dict:
    """The job's result, or the HTTP error that describes its failure."""
    if status_code == 504:
        raise HTTPException(
            status_code=504,
            detail={"error": {"message": "inference timed out", "type": "server_error"}},
        )

    if status_code != 200:
        raise HTTPException(
            status_code=status_code,
            detail={"error": {"message": "job not found", "type": "server_error"}},
        )

    if poll.get("status") == "error":
        message = (poll.get("result") or {}).get("error", "inference failed")

        if poll.get("code") == StatusCode.OUTPUT_INVALID:
            raise HTTPException(
                status_code=422,
                detail={"error": {"message": message, "type": "output_invalid"}},
            )

        raise HTTPException(
            status_code=500,
            detail={"error": {"message": message, "type": "server_error"}},
        )

    return poll.get("result") or {}


# ---------------------------------------------------------------------------
# Streaming
# ---------------------------------------------------------------------------


async def _sse_chunks(
    completion_id: str,
    created: int,
    model: str,
    content: str | None,
    tool_calls: list[ToolCall] | None,
    finish_reason: str,
):
    """Yield a fixed sequence of SSE chunks for a completed result.

    Generation is a single blocking call, so this frames a finished
    result in the shape OpenAI clients expect; it does not stream tokens.
    Tool calls carry their index, which clients use to assemble them.
    """
    def chunk(delta: ChatCompletionChunkDelta, finish: str | None = None) -> str:
        c = ChatCompletionChunk(
            id=completion_id,
            created=created,
            model=model,
            choices=[ChatCompletionChunkChoice(delta=delta, finish_reason=finish)],
        )
        return "data: %s\n\n" % c.model_dump_json(exclude_none=True)

    yield chunk(ChatCompletionChunkDelta(role="assistant"))

    if content is not None or tool_calls:
        deltas = (
            [ToolCallDelta(index=i, **tc.model_dump()) for i, tc in enumerate(tool_calls)]
            if tool_calls else None
        )
        yield chunk(ChatCompletionChunkDelta(content=content, tool_calls=deltas))

    yield chunk(ChatCompletionChunkDelta(), finish_reason)

    yield "data: [DONE]\n\n"


