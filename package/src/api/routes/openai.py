@router.get("/v1/models", response_model=ModelsResponse)
async def list_models(request: Request) -> ModelsResponse:
    """The instruct models in the catalogue, read on every call."""
    db_models = get_models_by_type(
        backend=request.app.state.table_backend,
        table=request.app.state.model_catalogue_table,
        model_type=ModelType.INSTRUCT,
    )

    return ModelsResponse(
        data=[ModelObject(id=m.name, created=0, owned_by=m.provider.value) for m in db_models]
    )


@router.post("/v1/chat/completions")
async def chat_completions(
    body: ChatCompletionRequest,
    request: Request,
):
    """OpenAI-compatible chat completions.

    Submits to the Marigold instruct queue, polls until terminal, and
    returns in OpenAI chat completion format.
    """
    _check_tool_choice(body.tool_choice)

    table_backend = request.app.state.table_backend
    queue_backend = request.app.state.queue_backend
    results_cache = request.app.state.results_cache
    table = request.app.state.model_catalogue_table

    user_id = "openai-local"

    submission_body = {
        "model": body.model,
        "messages": [_to_instruct_message(m) for m in body.messages],
        "temperature": body.temperature,
        "max_tokens": body.max_tokens,
    }
    if body.top_p is not None:
        submission_body["top_p"] = body.top_p
    if body.top_k is not None:
        submission_body["top_k"] = body.top_k
    if body.seed is not None:
        submission_body["seed"] = body.seed
    if body.tools is not None:
        submission_body["tools"] = body.tools
    if body.tool_choice == "none":
        submission_body["tool_choice"] = "none"
    if body.response_format is not None:
        submission_body["response_format"] = body.response_format
    if body.chat_template_kwargs:
        submission_body["chat_template_kwargs"] = body.chat_template_kwargs

    application_id = request.headers.get(APPLICATION_HEADER)
    if application_id:
        submission_body["application_id"] = application_id

    code, resp = handle_submission(
        user_id=user_id,
        body=submission_body,
        model_type=ModelType.INSTRUCT,
        catalogue_backend=table_backend,
        catalogue_table=table,
        queue_backend=queue_backend,
        notification_backend=None,
        results_cache=results_cache,
        topic=None,
    )

    if code != 200 or "message_id" not in resp:
        raise HTTPException(status_code=code, detail={"error": resp})

    message_id = resp["message_id"]
    status_code, poll = await _poll(user_id, message_id, results_cache)
    result = _result_or_raise(status_code, poll)

    choices = result.get("choices", [])
    choice0 = choices[0] if choices else {}
    content = choice0.get("content")
    raw_tool_calls = choice0.get("tool_calls") or []
    tool_calls = _from_instruct_tool_calls(raw_tool_calls, message_id) if raw_tool_calls else None

    usage = result.get("usage", {})
    input_tokens = usage.get("input_tokens", 0)
    output_tokens = usage.get("output_tokens", 0)
    finish_reason = "tool_calls" if tool_calls else result.get("finish_reason", "stop")
    completion_id = "chatcmpl-" + message_id[:8]
    created = int(time.time())

    if body.stream:
        return StreamingResponse(
            _sse_chunks(completion_id, created, body.model, content, tool_calls, finish_reason),
            media_type="text/event-stream",
        )

    return ChatCompletionResponse(
        id=completion_id,
        created=created,
        model=body.model,
        choices=[
            ChatCompletionChoice(
                index=0,
                message=ChatMessage(role="assistant", content=content, tool_calls=tool_calls),
                finish_reason=finish_reason,
            )
        ],
        usage=UsageStats(
            prompt_tokens=input_tokens,
            completion_tokens=output_tokens,
            total_tokens=input_tokens + output_tokens,
        ),
    )


@router.post("/v1/embeddings")
async def create_embeddings(body: EmbeddingRequest, request: Request) -> EmbeddingResponse:
    """OpenAI-compatible text embeddings.

    Accepts a single string or a list of strings; each is submitted as a
    separate job and results are collected in order.
    """
    logger.info(
        "embeddings request: model=%s input_type=%s",
        body.model,
        type(body.input).__name__,
    )

    table_backend = request.app.state.table_backend
    queue_backend = request.app.state.queue_backend
    results_cache = request.app.state.results_cache
    table = request.app.state.model_catalogue_table

    user_id = "openai-local"
    application_id = request.headers.get(APPLICATION_HEADER)

    inputs = body.input if isinstance(body.input, list) else [body.input]
    total_tokens = 0
    embedding_data = []

    for i, text in enumerate(inputs):
        submission_body = {"model": body.model, "input": text}
        if application_id:
            submission_body["application_id"] = application_id

        code, resp = handle_submission(
            user_id=user_id,
            body=submission_body,
            model_type=ModelType.TEXT_EMBEDDING,
            catalogue_backend=table_backend,
            catalogue_table=table,
            queue_backend=queue_backend,
            notification_backend=None,
            results_cache=results_cache,
            topic=None,
        )

        if code != 200 or "message_id" not in resp:
            raise HTTPException(status_code=400, detail={"error": resp})

        status_code, poll = await _poll(user_id, resp["message_id"], results_cache)
        result = _result_or_raise(status_code, poll)

        total_tokens += result.get("usage", {}).get("input_tokens", 0)
        embedding_data.append(EmbeddingData(index=i, embedding=result.get("embedding", [])))

    return EmbeddingResponse(
        model=body.model,
        data=embedding_data,
        usage=UsageStats(
            prompt_tokens=total_tokens,
            completion_tokens=0,
            total_tokens=total_tokens,
        ),
    )
